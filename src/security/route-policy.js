/** The policy entry governing a request path, or null (=> refuse). Literal entries win over patterns because they are checked in table order and the table is sorted specific-first for prefixes. */
export function classifyRoute(pathname) {
  for (const {entry, test} of compiled) if (test(pathname)) return entry;
  return null;
}
