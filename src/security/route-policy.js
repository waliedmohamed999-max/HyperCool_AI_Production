// Route access policy for the legacy /api surface (src/application.js) and the portal prefixes.
//
// Every /api route that is reachable must be listed here with an access class; a request whose path matches no entry is refused
// (default deny), so a new route cannot ship without an explicit decision. The class is enforced centrally in application.js
// (platform_admin / platform_operator / minimum workspace role) IN ADDITION to the check each handler performs itself, and
// tests/route-policy.test.js fails when a route declared in application.js is missing from this table.
//
// access classes
//   public              no session (login, signup, password reset, invitation preview, the embeddable chat widget, health)
//   webhook             called by an external system, authenticated by its own signature/secret (never a session)
//   internal            called by the operator's scheduler/automation with a shared token
//   authenticated_user  needs a session but no workspace (account settings, workspace switcher, accepting an invitation)
//   workspace_member    needs a session AND membership of the active workspace; `roles` is the minimum workspace role set;
//                       every query is scoped by the server-resolved tenant id
//   platform_operator   platform-global state: platform admin, or the owner of the operator's own (default) workspace
//   platform_admin      allow-listed platform administrators only (PLATFORM_ADMIN_USERNAMES)
//   partner             partner-program routes (own module: src/partners/routes.js)
//   merchant            merchant portal routes (own module: src/client/routes.js)
//
// Merchant-only accounts (members of a merchant workspace that use /client) may reach only public, webhook and
// authenticated_user routes of this table; everything else answers 403 MERCHANT_USE_CLIENT_PORTAL.

